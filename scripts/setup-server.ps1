<#
.SYNOPSIS
    InvasionCore のテスト用ローカルサーバーを作る。

.DESCRIPTION
    リポジトリ直下の server\（既定）に Paper サーバーを用意する。何度実行してもよく、
    既にあるファイル（server.properties・ワールド等）は上書きしない。

    - Paper の jar は run\ に同じビルドがあればコピーし、無ければ PaperMC から取得する。
      どちらの場合も公式の SHA-256 と照合する。
    - テスト向けの server.properties を書く（フラットワールド・スポーン保護なし・難易度ノーマル）。
    - start.cmd を書く。起動のたびに target\ の最新のプラグイン jar を plugins\ にコピーするので、
      「build.cmd package → start.cmd」だけで最新版を試せる。

    Minecraft の EULA には自分で同意すること（-AcceptEula を付けるか、eula.txt を自分で書き換える）。

.PARAMETER Path
    サーバーを作るフォルダ。既定はリポジトリ直下の server\。

.PARAMETER Port
    サーバーのポート。既定は 25565（クライアントから "localhost" だけで入れる）。

.PARAMETER NormalWorld
    通常の地形で生成する。既定は侵略Mobの挙動を観察しやすいフラットワールド。

.PARAMETER AcceptEula
    https://aka.ms/MinecraftEULA を読んで同意した場合に付ける。eula.txt に eula=true を書く。

.EXAMPLE
    scripts\setup-server.cmd -AcceptEula
#>
param(
    [string]$Path,
    [int]$Port = 25565,
    [switch]$NormalWorld,
    [switch]$AcceptEula
)

$ErrorActionPreference = 'Stop'
# Windows PowerShell 5.1 の進捗表示は大きなダウンロードを極端に遅くする
$ProgressPreference = 'SilentlyContinue'

# pom.xml の paper.version（26.2.build.92-stable）と揃えること。
# SHA-256 は https://fill.papermc.io/v3/projects/paper/versions/26.2/builds/92 の値。
$PaperVersion = '26.2'
$PaperBuild = 92
$PaperSha256 = '059d00bbce0fa1707739618b3276f5c80b9655dc0f964306fa799a9c7cb01cc2'

$repo = Split-Path -Parent $PSScriptRoot
if (-not $Path) {
    $Path = Join-Path $repo 'server'
}
$Path = [IO.Path]::GetFullPath($Path)
$jarName = "paper-$PaperVersion-$PaperBuild.jar"
$utf8 = New-Object Text.UTF8Encoding($false)

function Write-CrLf([string]$file, [string]$text, [Text.Encoding]$encoding) {
    [IO.File]::WriteAllText($file, ($text -replace "`r?`n", "`r`n"), $encoding)
}

Write-Host "[setup] サーバーフォルダ: $Path"
New-Item -ItemType Directory -Force -Path $Path | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $Path 'plugins') | Out-Null

# ---------- Paper 本体 ----------
$jar = Join-Path $Path $jarName
if (-not (Test-Path $jar)) {
    $local = Join-Path $repo "run\$jarName"
    if (Test-Path $local) {
        Copy-Item $local $jar
        Write-Host "[setup] run\ から $jarName をコピーした"
    } else {
        [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
        $api = "https://fill.papermc.io/v3/projects/paper/versions/$PaperVersion/builds/$PaperBuild"
        Write-Host "[setup] PaperMC から $jarName を取得する（約 60MB）"
        $build = Invoke-RestMethod -Uri $api -UserAgent 'InvasionCore-setup'
        Invoke-WebRequest -Uri $build.downloads.'server:default'.url -OutFile $jar -UserAgent 'InvasionCore-setup'
    }
}
$hash = (Get-FileHash $jar -Algorithm SHA256).Hash
if ($hash -ne $PaperSha256.ToUpperInvariant()) {
    Remove-Item $jar
    throw "$jarName のチェックサムが公式の値と一致しない（$hash）。削除したので再実行すること。"
}
Write-Host "[setup] $jarName のチェックサムを確認した"

# ---------- server.properties ----------
$props = Join-Path $Path 'server.properties'
if (-not (Test-Path $props)) {
    $levelType = if ($NormalWorld) { 'minecraft\:normal' } else { 'minecraft\:flat' }
    # difficulty=peaceful だと敵対Mobが消されて侵略Mobも即座に消滅するので、必ず normal 以上にする。
    # spawn-protection=0 にしないと、OP 以外がスポーン付近にネクサスや壁を置けない。
    # allow-flight=true はボスの吹き飛ばしや足場で「飛行」と誤判定されてキックされるのを防ぐ。
    Write-CrLf $props @"
motd=InvasionCore test server
server-port=$Port
query.port=$Port
level-type=$levelType
generate-structures=false
difficulty=normal
spawn-protection=0
allow-flight=true
online-mode=true
view-distance=10
simulation-distance=10
"@ $utf8
    Write-Host "[setup] server.properties を書いた（ポート $Port）"
} else {
    Write-Host "[setup] server.properties は既にあるので触らない"
}

# ---------- EULA ----------
$eula = Join-Path $Path 'eula.txt'
if ($AcceptEula) {
    Write-CrLf $eula @"
#By changing the setting below to TRUE you are indicating your agreement to our EULA (https://aka.ms/MinecraftEULA).
eula=true
"@ $utf8
    Write-Host "[setup] eula.txt に同意を記録した"
} elseif (-not (Test-Path $eula)) {
    Write-CrLf $eula @"
#By changing the setting below to TRUE you are indicating your agreement to our EULA (https://aka.ms/MinecraftEULA).
eula=false
"@ $utf8
}

# ---------- start.cmd ----------
# cmd.exe は OEM コードページで読むので ASCII のみで書く。
Write-CrLf (Join-Path $Path 'start.cmd') @"
@echo off
REM InvasionCore local test server (generated by scripts\setup-server.ps1).
REM Copies the newest plugin jar from the repository's target folder, then starts Paper.
REM NOTE: keep this file ASCII-only - cmd.exe reads it in the OEM codepage.

setlocal
cd /d "%~dp0"
set "REPO=$repo"
set "SERVER_JAR=$jarName"

findstr /i /c:"eula=true" eula.txt >nul 2>&1
if errorlevel 1 (
    echo [ERROR] Read https://aka.ms/MinecraftEULA and set eula=true in eula.txt first.
    pause
    exit /b 1
)

if exist "%REPO%\build.local.cmd" call "%REPO%\build.local.cmd"
if not defined JAVA_HOME (
    for /d %%D in (
        "%USERPROFILE%\.jdks\openjdk-25*"
        "%USERPROFILE%\.jdks\openjdk-26*"
        "%USERPROFILE%\.jdks\temurin-25*"
        "%USERPROFILE%\.jdks\temurin-26*"
        "C:\tools\jdk-25*"
        "C:\tools\jdk-26*"
        "%ProgramFiles%\Eclipse Adoptium\jdk-25*"
        "%ProgramFiles%\Eclipse Adoptium\jdk-26*"
    ) do if exist "%%~D\bin\java.exe" set "JAVA_HOME=%%~D"
)
if not exist "%JAVA_HOME%\bin\java.exe" (
    echo [ERROR] JDK 25+ not found. Set JAVA_HOME in %REPO%\build.local.cmd.
    pause
    exit /b 1
)

set "PLUGIN="
for %%F in ("%REPO%\target\InvasionCore-*.jar") do set "PLUGIN=%%~fF"
if defined PLUGIN (
    copy /y "%PLUGIN%" "plugins\" >nul
    echo [start] plugin: %PLUGIN%
) else (
    echo [WARN] No plugin jar in %REPO%\target. Run build.cmd package first.
)
echo [start] JAVA_HOME=%JAVA_HOME%

REM -Dstdout.encoding=UTF-8 is required on Windows, otherwise Japanese logs are mojibake.
"%JAVA_HOME%\bin\java.exe" -Xms1G -Xmx2G -XX:+UseG1GC ^
    -Dfile.encoding=UTF-8 -Dstdout.encoding=UTF-8 -Dstderr.encoding=UTF-8 ^
    -jar "%SERVER_JAR%" nogui

pause
"@ ([Text.Encoding]::ASCII)

Write-Host ''
Write-Host '[setup] 完了。次の手順:'
if (-not $AcceptEula -and -not (Select-String -Path $eula -Pattern 'eula=true' -Quiet)) {
    Write-Host '  0. https://aka.ms/MinecraftEULA を読み、同意するなら eula.txt を eula=true にする'
}
Write-Host '  1. リポジトリ直下で build.cmd package'
Write-Host "  2. $Path\start.cmd を実行"
Write-Host "  3. サーバーのコンソールで op <自分のMCID>"
Write-Host "  4. Minecraft $PaperVersion で localhost:$Port に接続"
